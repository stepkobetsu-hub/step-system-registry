const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync(__dirname+'/Index.html','utf8'),script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const dom=new JSDOM(html,{runScripts:'outside-only',url:'https://accounting.example.test'}),w=dom.window,d=w.document,ui=dom.getInternalVMContext();
w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};w.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');};
let success,requests=[],opened=[];
w.google={script:{run:{withSuccessHandler(fn){success=fn;return this;},withFailureHandler(){return this;},getInvoiceSettings(){},startInvoiceSearch(...args){requests.push(args);}}}};
w.open=(...args)=>opened.push(args);
vm.runInContext(script,ui);
vm.runInContext("sessionToken='test-token';entries=[{id:'first',serviceName:'Google Play（first）',account:'first@example.test'},{id:'second',serviceName:'Google Play（second）',account:'second@example.test'}]",ui);
const entry=vm.runInContext('entries',ui);
d.getElementById('grid').innerHTML=entry.map((e,i)=>w.cardHtml(e,i)).join('');
assert.equal(d.querySelectorAll('.invoice-card-import').length,2);
for(const button of d.querySelectorAll('.invoice-card-import'))assert.equal(button.previousElementSibling.className,'editIcon');
const settings={vendors:[{id:'googleplay',name:'Google Play',builtin:true}],mailbox:'first@example.test',folderUrl:'https://drive.google.com/test',folderName:'Test',ready:true,healthy:true};
d.getElementById('invoiceMonth').value='2026-09';
w.openGooglePlayInvoices('first');success(settings);
assert.equal(d.getElementById('invoiceVendor').value,'googleplay');
assert.equal(vm.runInContext('invoiceAccount',ui),'first@example.test');
assert.equal(vm.runInContext('invoiceExternal',ui),false);
w.searchInvoices();assert.deepEqual(requests,[['googleplay','2026-09','first@example.test','test-token']]);
